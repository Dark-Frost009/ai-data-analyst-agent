def test_query_planner_does_not_execute_sql():
    """
    QueryPlanner should only call the LLM.

    SQL execution belongs to SQLExecutor and must not happen inside the
    planner.
    """
    llm = _mock_llm("SELECT COUNT(*) FROM dataset")

    planner = QueryPlanner(llm_client=llm)

    result = planner.plan(
        "How many rows are there?",
        _dataset_profile(),
    )

    assert result == "SELECT COUNT(*) FROM dataset"

    # The only dependency interaction in this test is the LLM call.
    llm.generate_text.assert_called_once()


