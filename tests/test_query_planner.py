def _dataset_profile() -> DatasetProfile:
    """Return a small realistic dataset profile for planner tests."""
    return DatasetProfile(
        row_count=100,
        column_count=4,
        columns=[
            ColumnProfile(
                name="city",
                pandas_dtype="object",
                inferred_type="string",
                null_count=0,
                null_percentage=0.0,
                unique_count=5,
            ),
            ColumnProfile(
                name="category",
                pandas_dtype="object",
                inferred_type="string",
                null_count=2,
                null_percentage=2.0,
                unique_count=3,
            ),
            ColumnProfile(
                name="revenue",
                pandas_dtype="float64",
                inferred_type="float",
                null_count=1,
                null_percentage=1.0,
                unique_count=90,
                min=10.5,
                max=9999.99,
                mean=1250.75,
            ),
            ColumnProfile(
                name="orders",
                pandas_dtype="int64",
                inferred_type="integer",
                null_count=0,
                null_percentage=0.0,
                unique_count=50,
                min=1,
                max=500,
                mean=100.0,
            ),
        ],
        sample_rows=[
            {
                "city": "Kolkata",
                "category": "Food",
                "revenue": 1200.50,
                "orders": 10,
            },
            {
                "city": "Delhi",
                "category": "Grocery",
                "revenue": 900.00,
                "orders": 7,
            },
        ],
    )


def _mock_llm(response: str) -> MagicMock:
    """Create a mocked Bedrock client returning the supplied response."""
    client = MagicMock()
    client.generate_text.return_value = response
    return client


