def test_plan_generates_sql_from_question():
    """Planner should return SQL generated by the LLM."""
    llm = _mock_llm(
        "SELECT city, SUM(revenue) AS total_revenue "
        "FROM dataset "
        "GROUP BY city "
        "ORDER BY total_revenue DESC "
        "LIMIT 5"
    )

    planner = QueryPlanner(llm_client=llm)

    result = planner.plan(
        "What are the top 5 cities by revenue?",
        _dataset_profile(),
    )

    assert result == (
        "SELECT city, SUM(revenue) AS total_revenue "
        "FROM dataset "
        "GROUP BY city "
        "ORDER BY total_revenue DESC "
        "LIMIT 5"
    )


def test_plan_calls_llm_once():
    """One planning request should result in exactly one LLM call."""
    llm = _mock_llm("SELECT COUNT(*) FROM dataset")

    planner = QueryPlanner(llm_client=llm)

    planner.plan(
        "How many records are there?",
        _dataset_profile(),
    )

    llm.generate_text.assert_called_once()


def test_plan_uses_zero_temperature():
    """SQL generation should be deterministic by default."""
    llm = _mock_llm("SELECT COUNT(*) FROM dataset")

    planner = QueryPlanner(llm_client=llm)

    planner.plan(
        "How many rows are there?",
        _dataset_profile(),
    )

    kwargs = llm.generate_text.call_args.kwargs

    assert kwargs["temperature"] == 0.0
    assert kwargs["max_tokens"] == 1024


